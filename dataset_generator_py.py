import pandas as pd
import random

def generate_datasets(n):
    applicants = []
    job_postings = []

    # Generate Applicants (Array 1)
    for i in range(1, n + 1):
        skill_level = random.randint(1, 100) # Skill scored from 1 to 100
        experience = random.randint(0, 15)   # 0 to 15 years of experience
        # Salary expectation scales with experience and skill, plus some randomness
        expected_salary = int((skill_level * 250) + (experience * 1500) + random.randint(15000, 25000))

        applicants.append({
            "Applicant_ID": f"A_{i}",
            "Skill_Level": skill_level,
            "Years_Experience": experience,
            "Expected_Salary": expected_salary
        })

    # Generate Job Postings (Array 2)
    for i in range(1, n + 1):
        required_skill = random.randint(10, 95)
        required_experience = random.randint(0, 10)
        # Salary offer scales with requirements, plus some variance to simulate good/bad offers
        salary_offer = int((required_skill * 250) + (required_experience * 1500) + random.randint(12000, 28000))

        job_postings.append({
            "Job_ID": f"J_{i}",
            "Required_Skill_Level": required_skill,
            "Required_Experience": required_experience,
            "Salary_Offer": salary_offer
        })

    # Convert to DataFrames
    df_applicants = pd.DataFrame(applicants)
    df_jobs = pd.DataFrame(job_postings)

    # Save to CSV files
    df_applicants.to_csv(f"applicants_N{n}.csv", index=False)
    df_jobs.to_csv(f"jobs_N{n}.csv", index=False)
    print(f"Successfully generated datasets for N={n}")

# Generate the specific batch sizes required for the complexity metrics
batch_sizes = [100, 500, 2500]

for size in batch_sizes:
    generate_datasets(size)